interface PatternRule {
  regex: RegExp;
  replace: (...args: string[]) => string;
}

const FIL_PATTERNS: PatternRule[] = [
  {
    regex: /^Showing (\d+) to (\d+) of (\d+)(?: (results|records|items|trainees|users|logs))?$/i,
    replace: (_, from, to, total) => `Nagpapakita ng ${from} hanggang ${to} sa ${total} rekord`,
  },
  {
    regex: /^Page (\d+) of (\d+)$/i,
    replace: (_, page, total) => `Pahina ${page} ng ${total}`,
  },
  {
    regex: /^Joined (.+)$/,
    replace: (_, date) => `Sumali noong ${date}`,
  },
  {
    regex: /^Earned on (.+)$/,
    replace: (_, date) => `Nakamit noong ${date}`,
  },
  {
    regex: /^(\d+) local admins? across all tenants$/,
    replace: (_, count) => `${count} lokal na admin sa lahat ng tenant`,
  },
  {
    regex: /^(\d+) local admins? matching "(.+)"$/,
    replace: (_, count, query) => `${count} lokal na admin na tumutugma sa "${query}"`,
  },
  {
    regex: /^(\d+) unread messages?$/i,
    replace: (_, count) => `${count} hindi pa nababasang mensahe`,
  },
  {
    regex: /^(\d+) pending items?$/i,
    replace: (_, count) => `${count} nakabinbing rekord`,
  },
];

export function interpolateParams(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) =>
    params[key] !== undefined ? String(params[key]) : `{${key}}`
  );
}

/**
 * Translates an exact or parameterized English UI phrase into Natural Modern Filipino,
 * preserving surrounding whitespace and trailing required markers (" *", ":").
 */
export function translateUiPhrase(raw: string, language: SupportedLanguage, params?: Record<string, string | number>): string {
  const withParams = interpolateParams(raw, params);
  if (language === 'en' || !withParams) return withParams;

  const match = withParams.match(/^(\s*)(.*?)(\s*(?:\*|:)?\s*)$/);
  if (!match) return withParams;

  const [, leading, core, trailing] = match;
  if (!core || core.length < 2) return withParams;

  const exact = FIL_PHRASES[core];
  if (exact) {
    return `${leading}${exact}${trailing}`;
  }

  // Also check if trailing had ':' that belongs to the phrase itself (e.g., "Records per page:")
  const trimmedFull = withParams.trim();
  const exactFull = FIL_PHRASES[trimmedFull];
  if (exactFull) {
    const wsMatch = withParams.match(/^(\s*).*?(\s*)$/);
    return wsMatch ? `${wsMatch[1]}${exactFull}${wsMatch[2]}` : exactFull;
  }

  for (const rule of FIL_PATTERNS) {
    if (rule.regex.test(core)) {
      const replaced = core.replace(rule.regex, (...args) => rule.replace(...(args as string[])));
      return `${leading}${replaced}${trailing}`;
    }
  }

  return withParams;
}
